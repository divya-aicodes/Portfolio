create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  name varchar(80) not null check (char_length(name) between 2 and 80),
  email varchar(254) not null,
  message varchar(1500) not null check (char_length(message) between 20 and 1500),
  created_at timestamptz not null default now()
);

create index if not exists messages_created_at_idx on public.messages (created_at desc);

-- The Flask server connects with the private database connection string.
-- Do not expose this table through the public Supabase API.
alter table public.messages enable row level security;
